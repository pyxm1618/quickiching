// Deliberately scoped delivery assets. PNG masters and existing detail delivery stay untouched.
import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const definitions = [
  ['stageDesktop', 'ritual/bg-stage-master-clean.png', 1671],
  ['stageMobile', 'ritual/bg-stage-mobile-600.webp'],
  ['stagePortrait', 'ritual/bg-stage-portrait-crop.webp'],
  ['questionDesktop', 'ritual/question-parchment-crop.png'],
  ['questionMobile', 'ritual/question-parchment-mobile-crop.webp'],
  ['resultDesktop', 'ritual/hexagram-result-card-blank.png', 1670],
  ['resultMobile', 'ritual/hexagram-result-card-mobile.webp'],
  ['accountCoins', 'account/antique-coins-clean.png', 900, true],
  ['platformDesktop', 'hexagrams/ritual-platform.png', 1600],
  ['platformMobile', 'hexagrams/ritual-platform.png', 800],
  ['coinFrontDesktop', 'ritual/coin-front-master.png', 1024],
  ['coinBackDesktop', 'ritual/coin-back-master.png', 1024],
  ['coinFrontMobile', 'ritual/coin-front-mobile-512.png', 512, true],
  ['coinBackMobile', 'ritual/coin-back-mobile-512.png', 512, true],
];
const hash = buffer => createHash('sha256').update(buffer).digest('hex');
await mkdir('public/performance', { recursive: true });
const manifest = {}, urls = {};
for (const [name, source, width, lossless = false] of definitions) {
  const original = await readFile(`public/${source}`);
  const options = width ? { lossless, quality: 95, alphaQuality: 100, effort: 6 } : null;
  const encoded = width ? await sharp(original).resize({ width, withoutEnlargement: true }).webp(options).toBuffer() : original;
  const extension = width ? 'webp' : source.split('.').at(-1);
  const url = `/performance/${name}.${hash(encoded).slice(0, 16)}.${extension}`;
  await writeFile(`public${url}`, encoded);
  const metadata = await sharp(encoded).metadata();
  urls[name] = url;
  manifest[name] = { source, sourceSha256: hash(original), sourceBytes: original.length, url, sha256: hash(encoded), bytes: encoded.length, width: metadata.width, height: metadata.height, options };
  console.log(`${name}: ${original.length} → ${encoded.length} bytes ${url}`);
}
await writeFile('docs/performance/pr-76-assets.json', JSON.stringify(manifest, null, 2) + '\n');
await writeFile('src/lib/visual-runtime-assets.ts', '// Generated by scripts/generate-performance-assets.mjs. Content hashes permit immutable caching.\nexport const visualRuntimeAssets = ' + JSON.stringify(urls, null, 2) + ' as const;\n');
// CSS and preload references intentionally remain explicit; update them from this manifest
// when regenerating; the asset gate verifies source and delivery hashes.

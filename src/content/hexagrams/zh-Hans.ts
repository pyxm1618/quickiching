function buildContent(number: number): ZhHansHexagramDetailContent {
  const summary = SUMMARY_BY_NUMBER[number];
  const modern = MODERN_CONTENT_BY_NUMBER[number];
  const realityUnderstanding = REALITY_UNDERSTANDING_BY_NUMBER[number];
  const classical = CLASSICAL_HEXAGRAMS.find((entry) => entry.number === number);
  if (!summary || !modern || !realityUnderstanding || !classical) throw new Error("ZH_HANS_HEXAGRAM_CONTENT_MISSING: " + number);

  return {
    number,
    theme: summary.theme,
    coreMeaning: summary.coreMeaning,
    realityUnderstanding,
    ...modern,
    ...(SCENE_MODULES[number] ? { sceneModule: SCENE_MODULES[number] } : {}),
  };
}

export const ZH_HANS_HEXAGRAM_CONTENT = Object.fromEntries(
  CLASSICAL_HEXAGRAMS.map((hexagram) => [hexagram.number, buildContent(hexagram.number)]),
) as Record<number, ZhHansHexagramDetailContent>;

export function zhHansHexagramContent(number: number): ZhHansHexagramDetailContent {
  const content = ZH_HANS_HEXAGRAM_CONTENT[number];
  if (!content) throw new Error("ZH_HANS_HEXAGRAM_CONTENT_MISSING: " + number);
  return content;
}
